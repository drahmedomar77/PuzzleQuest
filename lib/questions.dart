import 'package:flutter/material.dart';

/// مستويات الصعوبة
enum Tier { easy, medium, hard }

extension TierX on Tier {
  String get label => switch (this) {
        Tier.easy => 'سهل',
        Tier.medium => 'متوسط',
        Tier.hard => 'صعب',
      };

  Color get color => switch (this) {
        Tier.easy => const Color(0xFF43A047),
        Tier.medium => const Color(0xFFFB8C00),
        Tier.hard => const Color(0xFFE53935),
      };

  /// الوقت المسموح لكل سؤال بالثواني
  int get seconds => switch (this) {
        Tier.easy => 25,
        Tier.medium => 20,
        Tier.hard => 15,
      };
}

class Question {
  final String text;
  final List<String> options;
  final int answer; // رقم الإجابة الصحيحة داخل options
  final String? explain;
  const Question(this.text, this.options, this.answer, [this.explain]);
}

